import math

print(f"π: {math.pi}")
print(f"e: {math.e}")
print(f"平方根: {math.sqrt(16)}")  # 4.0
print(f"对数: {math.log(100, 10)}")  # 2.0
print(f"正弦: {math.sin(math.pi/2)}")  # 1.0
print(f"阶乘: {math.factorial(5)}")  # 120
print(f"最大公约数: {math.gcd(12, 18)}")  # 6
print(f"向上取整: {math.ceil(3.14)}")  # 4
print(f"向下取整: {math.floor(3.14)}")  # 3
print(f"弧度转角度: {math.degrees(math.pi)}")  # 180.0